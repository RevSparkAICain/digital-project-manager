"""Write brand.json (the schema every skill in this repo reads) and tokens.css."""
import json
import os

import fonts

COMMENT = ("Generated by the brand-extract skill. provenance records where every value came "
           "from. Regenerate instead of hand-editing, and keep tokens.css in sync.")
STATUS_COMMENT = ("Optional functional status colors. Not extracted; when empty, reviewers "
                  "accept a conventional red, amber, or green used strictly as a status cue "
                  "and kept off primary brand elements.")
AVOID = ["colors not listed in this file", "gradients", "drop shadows", "3D effects"]
COLOR_KEYS = ("primary", "text", "textMuted", "background", "surface", "divider", "link",
              "accent1", "accent2", "accent3")
CSS_COLORS = (("primary", "--brand-primary"), ("text", "--brand-text"),
              ("textMuted", "--brand-text-muted"), ("background", "--brand-background"),
              ("surface", "--brand-surface"), ("divider", "--brand-divider"),
              ("link", "--brand-link"), ("accent1", "--brand-accent-1"),
              ("accent2", "--brand-accent-2"), ("accent3", "--brand-accent-3"))


def _xml_text(value):
    """The text with every character outside the XML 1.0 Char range removed (controls below
    0x20, U+FFFE, U+FFFF and lone surrogates), whitespace collapsed and trimmed."""
    if not value:
        return ""
    kept = "".join(ch for ch in value
                   if ord(ch) >= 0x20 and ord(ch) not in (0xFFFE, 0xFFFF)
                   and not 0xD800 <= ord(ch) <= 0xDFFF)
    return " ".join(kept.split())


def build_brand(profile, name, logo_file=None, templates=None):
    c, f = profile["colors"], profile["fonts"]
    name = _xml_text(name) or "Company"
    office = fonts.clean_family(_xml_text(f["body"])) or "Arial"
    office_heading = fonts.clean_family(_xml_text(f["heading"])) or office
    return {
        "$comment": COMMENT,
        "meta": {"name": "%s brand" % name, "organization": name, "placeholder": False,
                 "version": "1.0.0", "generatedBy": "brand-extract"},
        "colors": {k: c.get(k) for k in COLOR_KEYS},
        "chart": list(profile["chart"]),
        "status": {"$comment": STATUS_COMMENT, "good": None, "warning": None, "critical": None},
        "fonts": {"web": fonts.web_stack(office), "webHeading": fonts.web_stack(office_heading),
                  "webMono": fonts.MONO_STACK, "office": office, "officeHeading": office_heading},
        "usage": {"primaryAsAccent": True, "statusColorsOffBrandElements": True,
                  "linkUnderline": False},
        "avoid": list(AVOID),
        "logo": {"file": logo_file, "minWidthPx": None,
                 "rules": ["Use the supplied file as is: do not recolor, stretch, crop or "
                           "redraw it."] if logo_file else []},
        "templates": dict({"pptx": None, "docx": None, "xlsx": None}, **(templates or {})),
        "layout": dict(profile["layout"]),
        "provenance": {k: dict(v) for k, v in profile["provenance"].items()},
        "adjustments": list(profile["adjustments"]),
        "warnings": list(profile["warnings"]),
    }


def render_css(brand):
    org = brand["meta"]["organization"].replace("*/", "* /")
    stop = "" if org.endswith(".") else "."
    lines = ["/*",
             "  tokens.css: generated by brand-extract for %s%s" % (org, stop),
             "  Mirrors brand.json, which is the source of truth. Regenerate both together.",
             "*/",
             ":root {",
             "  /* colors */"]
    for key, var in CSS_COLORS:
        if brand["colors"].get(key):
            lines.append("  %s: %s;" % (var, brand["colors"][key]))
    lines += ["", "  /* chart series, in order */"]
    for i, hexv in enumerate(brand["chart"], 1):
        lines.append("  --brand-chart-%d: %s;" % (i, hexv))
    lines += ["",
              '  /* status colors: not extracted (see brand.json "status") */',
              "  --brand-status-good: initial;",
              "  --brand-status-warning: initial;",
              "  --brand-status-critical: initial;",
              "",
              "  /* type */",
              "  --brand-font: %s;" % brand["fonts"]["web"],
              "  --brand-font-heading: %s;" % brand["fonts"]["webHeading"],
              "  --brand-font-mono: %s;" % brand["fonts"]["webMono"]]
    layout = brand.get("layout", {})
    if layout.get("baseFontPx"):
        lines.append("  --brand-font-size-base: %gpx;" % layout["baseFontPx"])
    if layout.get("headingScale"):
        lines.append("  --brand-heading-scale: %g;" % layout["headingScale"])
    lines.append("}")
    return "\n".join(lines) + "\n"


def write_tokens(brand, out_dir):
    os.makedirs(out_dir, exist_ok=True)
    with open(os.path.join(out_dir, "brand.json"), "w", encoding="utf-8", newline="\n") as fh:
        json.dump(brand, fh, indent=2, ensure_ascii=False, allow_nan=False)  # strict JSON only
        fh.write("\n")
    with open(os.path.join(out_dir, "tokens.css"), "w", encoding="utf-8", newline="\n") as fh:
        fh.write(render_css(brand))
