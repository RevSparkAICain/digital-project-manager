"""Write the generated <slug>-brand/SKILL.md from a fixed template.

Only the paragraph between the blurb markers is free text; the agent running brand-extract
may rewrite it after a run. Everything else is filled from brand.json so it always matches
the profile.
"""
import json
import os
import re

BLURB_START = "<!-- blurb:start -->"
BLURB_END = "<!-- blurb:end -->"
SLUG = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")
BLURB_MAX = 800
DESC_ORG_MAX = 120
DEFAULT_ORG_MAX = 60
DEFAULT_LABEL_MAX = 60
DEFAULT_SOURCES_SHOWN = 5
DESCRIPTION_MAX = 1024
CONTROL = re.compile(r"[\x00-\x1f\x7f]")
MARKDOWN_LEAD = "#>-*+|`=~_"
NUMBERED_LEAD = re.compile(r"^\d+[.)]")


def slugify(name):
    return re.sub(r"[^a-z0-9]+", "-", name.lower()).strip("-") or "company"


def _strip_markers(text):
    """Remove HTML comment markers, repeating until none is left: one pass over "<<!--!--"
    would leave a fresh "<!--" behind."""
    while True:
        stripped = text.replace("<!--", "").replace("-->", "")
        if stripped == text:
            return text
        text = stripped


def _short(text, limit):
    return _strip_markers(text)[:limit]


def default_blurb(brand, sources):
    c, f = brand["colors"], brand["fonts"]
    accents = [_strip_markers(c[k]) for k in ("accent1", "accent2", "accent3") if c.get(k)]
    with_accents = (" with accents " + ", ".join(accents)) if accents else ""
    sources = sorted(sources)  # the generated skill must not change with argument order
    shown = [_short(s, DEFAULT_LABEL_MAX) for s in sources[:DEFAULT_SOURCES_SHOWN]]
    listed = ", ".join(shown)
    if len(sources) > DEFAULT_SOURCES_SHOWN:
        listed += ", and %d more" % (len(sources) - DEFAULT_SOURCES_SHOWN)
    return ("%s brand profile, extracted by brand-extract from %d source(s): %s. Primary color "
            "%s%s on a %s background with %s text. Headings use %s; body text uses %s."
            % (_short(brand["meta"]["organization"], DEFAULT_ORG_MAX), len(sources), listed,
               c["primary"], with_accents, c["background"], c["text"],
               _short(f["officeHeading"], DEFAULT_LABEL_MAX),
               _short(f["office"], DEFAULT_LABEL_MAX)))


def _clean_blurb(blurb):
    """Collapse whitespace, drop control characters, then reject or escape what would break
    the rendered page: an empty or comment-marker blurb, an over-long one, and a leading
    markdown construct (heading, quote, list, table, code, numbered item)."""
    text = " ".join(CONTROL.sub("", " ".join(blurb.split())).split())
    if not text or "<!--" in text or "-->" in text:
        raise ValueError("blurb must be one non-empty paragraph with no HTML comment markers")
    if len(text) > BLURB_MAX:
        raise ValueError("blurb must be at most %d characters" % BLURB_MAX)
    if text[0] in MARKDOWN_LEAD:
        text = "\\" + text
    else:
        m = NUMBERED_LEAD.match(text)
        if m:
            cut = m.end() - 1
            text = text[:cut] + "\\" + text[cut:]
    return text


def validate_blurb(text):
    """Return the blurb as the generated skill will carry it, or raise ValueError."""
    return _clean_blurb(text)


def render_skill(brand, slug, blurb):
    if not SLUG.fullmatch(slug):
        raise ValueError("slug must be lowercase letters, digits and single hyphens: %r" % slug)
    blurb = _clean_blurb(blurb)
    org = _strip_markers(brand["meta"]["organization"])
    short = org[:DESC_ORG_MAX]
    description = (
        "Apply the %s visual brand (colors, fonts, logo, chart palette, slide and page layout) "
        "to any deck, document, spreadsheet, chart, diagram or web page made for this company. "
        "Use whenever output should look on-brand for this company. Values come from "
        "brand.json, generated by the brand-extract skill." % short)
    if len(description) > DESCRIPTION_MAX:
        raise ValueError("description must be at most %d characters" % DESCRIPTION_MAX)
    c, f = brand["colors"], brand["fonts"]
    lines = [
        "---",
        "name: %s-brand" % slug,
        "description: " + json.dumps(description, ensure_ascii=False),
        "---",
        "",
        "# %s brand" % org,
        "",
        BLURB_START,
        blurb,
        BLURB_END,
        "",
        "## Colors",
        "",
        "| Role | Value |",
        "|---|---|",
    ]
    lines += ["| %s | `%s` |" % (k, v) for k, v in c.items() if v]
    lines += [
        "",
        "Chart series, in order: " + ", ".join("`%s`" % h for h in brand["chart"]),
        "",
        "## Fonts",
        "",
        "- Headings: %s (web stack `%s`)" % (f["officeHeading"], f["webHeading"]),
        "- Body: %s (web stack `%s`)" % (f["office"], f["web"]),
        "",
        "## Rules",
        "",
        "- Use only the colors above. Primary marks titles, key numbers and one focal element "
        "per page or slide; accents mark secondary series and highlights.",
        "- Body text uses the text color on the background color. White text sits only on the "
        "primary color.",
        "- Charts take the chart series in order and keep that order across related charts.",
        "- Start decks from the starter `.pptx` and documents from the starter `.docx` when they "
        "exist.",
        "- Status colors (red, amber, green) are a functional cue only and stay off brand "
        "elements.",
        "",
        "## Files",
        "",
        "Paths are relative to the folder that holds `brand.json`.",
        "",
        "- `brand.json`: every value, plus `provenance` recording where each one came from.",
        "- `tokens.css`: the same values as CSS custom properties for HTML and SVG.",
    ]
    for kind, noun in (("pptx", "deck"), ("docx", "document")):
        if brand["templates"].get(kind):
            lines.append("- `%s`: starter %s with the brand theme colors, fonts and layout."
                         % (brand["templates"][kind], noun))
    if brand["logo"]["file"]:
        lines.append("- `%s`: the logo, copied unchanged from the source." % brand["logo"]["file"])
    if brand["warnings"]:
        lines += ["", "## Defaulted values", "",
                  "These were not found in the sources and use defaults. Confirm them before "
                  "any external use:", ""]
        lines += ["- %s" % " ".join(w.split()) for w in brand["warnings"]]
    lines += ["", "## Regenerating", "",
              "Run brand-extract again on updated collateral. It rewrites `brand.json`, "
              "`tokens.css`, the templates and this file together, so do not hand-edit one "
              "without the others."]
    return "\n".join(lines) + "\n"


def write_skill(brand, out_dir, slug, blurb):
    text = render_skill(brand, slug, blurb)
    folder = os.path.join(out_dir, "%s-brand" % slug)
    os.makedirs(folder, exist_ok=True)
    path = os.path.join(folder, "SKILL.md")
    with open(path, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    return path
