"""Write starter template.pptx and template.docx carrying the brand theme, fonts and layout.

python-pptx and python-docx are imported inside each writer, so a missing library raises
ImportError for that template only; extract.py records it as a warning.
"""
import office_theme

STAMP_COMMENT = "Starter template generated by brand-extract"


def theme_colors(brand):
    """Theme slots from the brand: chart series fill accent1 to accent6 in order."""
    c, chart = brand["colors"], brand["chart"]
    slots = {"dk1": c["text"], "lt1": c["background"], "dk2": c["text"], "lt2": c["surface"],
             "hlink": c["link"], "folHlink": c["textMuted"]}
    for i in range(6):
        slots["accent%d" % (i + 1)] = chart[i]
    return slots


def _theme_fonts(brand):
    return {"major": brand["fonts"]["officeHeading"], "minor": brand["fonts"]["office"]}


def _stamp(props, org):
    # The library default templates carry their own author metadata; always overwrite it.
    props.author = org
    props.last_modified_by = "brand-extract"
    props.comments = STAMP_COMMENT
    props.title = "%s starter template" % org


def _scale_shapes(prs, rx, ry):
    """Stretch layout and master shapes to a new slide size. Layouts go first: a layout
    placeholder with no position of its own reads it from the still-unscaled master."""
    groups = [layout.shapes for layout in prs.slide_layouts] + [prs.slide_master.shapes]
    for shapes in groups:
        for shape in shapes:
            box = (shape.left, shape.top, shape.width, shape.height)
            if None in box:
                continue
            left, top, width, height = box
            shape.left, shape.top = int(left * rx), int(top * ry)
            shape.width, shape.height = int(width * rx), int(height * ry)


def write_pptx(brand, path):
    from pptx import Presentation
    from pptx.util import Inches
    prs = Presentation()
    layout = brand["layout"]
    # python-pptx refuses slide sizes outside 1 to 56 inches; clamp rather than abort the run.
    width_in, height_in = (min(max(float(layout[k]), 1.0), 56.0)
                           for k in ("slideWidthIn", "slideHeightIn"))
    new_w, new_h = Inches(width_in), Inches(height_in)
    _scale_shapes(prs, new_w / prs.slide_width, new_h / prs.slide_height)
    prs.slide_width, prs.slide_height = new_w, new_h
    org = brand["meta"]["organization"]
    slide = prs.slides.add_slide(prs.slide_layouts[0])
    slide.shapes.title.text = org
    slide.placeholders[1].text = STAMP_COMMENT
    slide = prs.slides.add_slide(prs.slide_layouts[1])
    slide.shapes.title.text = "Title and content"
    slide.placeholders[1].text = "Body text uses the theme body font and text color."
    _stamp(prs.core_properties, org)
    prs.save(path)
    office_theme.apply_theme(path, theme_colors(brand), _theme_fonts(brand))


def write_docx(brand, path):
    from docx import Document
    from docx.shared import Inches, RGBColor
    doc = Document()
    c, f = brand["colors"], brand["fonts"]

    def style(name, family, hexv):
        st = doc.styles[name]
        st.font.name = family
        st.font.color.rgb = RGBColor.from_string(hexv.lstrip("#"))

    style("Normal", f["office"], c["text"])
    for name in ("Title", "Heading 1", "Heading 2"):
        style(name, f["officeHeading"], c["primary"])
    margin = Inches(brand["layout"]["pageMarginIn"])
    for section in doc.sections:
        section.left_margin = margin
        section.right_margin = margin
    org = brand["meta"]["organization"]
    doc.add_paragraph(org, style="Title")
    doc.add_paragraph("Heading 1", style="Heading 1")
    doc.add_paragraph("Body text uses the brand body font and text color.")
    _stamp(doc.core_properties, org)
    doc.save(path)
    office_theme.apply_theme(path, theme_colors(brand), _theme_fonts(brand))
